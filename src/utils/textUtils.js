/**
 * Text and HTML sanitization utilities for Job Circular
 */

const MAX_CACHE_SIZE = 1200;
const stripCache = new Map();
const cleanOptionCache = new Map();
const sanitizeQuestionCache = new Map();

/**
 * Strips all HTML tags and decodes common HTML entities from a string.
 * Ensures clean plain-text output for card titles, organization names, and descriptions.
 * 
 * @param {string|object} input 
 * @returns {string}
 */
export function stripHtmlTags(input) {
  if (!input) return '';
  
  let str = input;
  if (typeof str === 'object') {
    str = str.bn || str.en || str.title || str.name || str.text || '';
  }
  if (typeof str !== 'string') {
    str = String(str || '');
  }

  // Fast cache lookup
  if (stripCache.has(str)) {
    return stripCache.get(str);
  }

  // 1. Decode entities first so encoded tags like &lt;p&gt; become <p>
  let cleaned = str
    .replace(/&lt;/g, '<')
    .replace(/&#60;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&#62;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&#39;/g, "'")
    .replace(/&#34;/g, '"')
    .replace(/&amp;/g, '&')
    .replace(/&#38;/g, '&')
    .replace(/&nbsp;/g, ' ')
    .replace(/&#160;/g, ' ');

  // 2. Replace block endings and line breaks with spaces so words do not concatenate
  cleaned = cleaned
    .replace(/<br\s*[\/]?>/gi, ' ')
    .replace(/<\/(p|div|h[1-6]|li|tr|th|td|blockquote)>/gi, ' ')
    .replace(/<[^>]*>/g, ' ');

  // 3. Decode any secondary entities (including numeric & hex)
  cleaned = cleaned
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&#39;/g, "'")
    .replace(/&#34;/g, '"')
    .replace(/&amp;/g, '&')
    .replace(/&#38;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&#60;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&#62;/g, '>')
    .replace(/&nbsp;/g, ' ')
    .replace(/&#160;/g, ' ')
    .replace(/&#(\d+);/g, (_, dec) => {
      try {
        return String.fromCharCode(parseInt(dec, 10));
      } catch {
        return '';
      }
    })
    .replace(/&#x([0-9a-fA-F]+);/g, (_, hex) => {
      try {
        return String.fromCharCode(parseInt(hex, 16));
      } catch {
        return '';
      }
    });

  // 4. Final tag cleanup: eliminate any leftover tags (e.g. <p>, </p>, <span ...>, etc.)
  cleaned = cleaned.replace(/<[^>]*>/g, ' ');

  // 5. In case of stray, unclosed, or malformed tags like "<p " or "<p>" at the beginning of snippet
  cleaned = cleaned.replace(/<\/?\w+[^>]*>?/gi, '');

  // Collapse multiple whitespaces and newlines
  const result = cleaned.replace(/\s+/g, ' ').trim();
  if (stripCache.size >= MAX_CACHE_SIZE) stripCache.clear();
  stripCache.set(str, result);
  return result;
}

/**
 * Sanitizes rich text HTML for descriptions to prevent invisible text
 * caused by dark-mode copied styles (e.g. color: rgb(255, 255, 255)).
 * 
 * @param {string} html 
 * @returns {string}
 */
export function sanitizeRichHtml(html) {
  if (!html || typeof html !== 'string') return '';
  return html
    .replace(/<script\b[^<]*(?:(?!<\/script>)<[^<]*)*<\/script>/gi, '')
    .replace(/color:\s*(#fff(fff)?|white|rgb\(\s*255\s*,\s*255\s*,\s*255\s*\))/gi, 'color: inherit');
}

/**
 * Cleans option text by removing duplicated choice prefixes (e.g. "(a)", "A.", "(ক)", "ক)"),
 * stripping HTML tags, and decoding entities like &nbsp; into clean plain text.
 */
export function cleanOptionText(input) {
  if (!input) return '';
  let str = input;
  if (typeof str === 'object') {
    str = str.bn || str.en || str.title || str.name || str.text || '';
  }
  str = String(str || '');

  if (cleanOptionCache.has(str)) {
    return cleanOptionCache.get(str);
  }

  // Strip all HTML tags and decode entities first
  let cleaned = stripHtmlTags(str);

  // Remove duplicated option prefix if present in the text
  const prefixPatterns = [
    /^\([a-d]\)\s*/i,   // (a), (b), (c), (d)
    /^[a-d][\.\)]\s*/i, // a., a), b., b)
    /^\([ক-ঘ]\)\s*/,   // (ক), (খ), (গ), (ঘ)
    /^[ক-ঘ][\।\)]\s*/, // ক।, ক), খ।, খ)
    /^\(\d+\)\s*/,     // (1), (2)
    /^\d+[\.\)]\s*/    // 1., 1)
  ];
  prefixPatterns.forEach(pattern => {
    cleaned = cleaned.replace(pattern, '');
  });

  const result = cleaned.trim();
  if (cleanOptionCache.size >= MAX_CACHE_SIZE) cleanOptionCache.clear();
  cleanOptionCache.set(str, result);
  return result;
}

/**
 * Sanitizes rich text HTML for questions and explanations.
 * - Strips harmful scripts.
 * - Removes intrusive inline styling generated by contentEditable/browsers
 *   (font-family, font-size, line-height, conflicting rgb colors) while keeping
 *   valid HTML markup like <b>, <i>, <u>, <sup>, <sub>, <code>, <p>, <br>, <strong>, etc.
 * - Converts non-breaking spaces &nbsp; to normal spaces.
 * - Unwraps redundant styled spans.
 */
export function sanitizeQuestionHtml(input) {
  if (!input) return '';
  let html = input;
  if (typeof html === 'object') {
    html = html.bn || html.en || html.title || html.name || html.text || '';
  }
  html = String(html || '');

  if (sanitizeQuestionCache.has(html)) {
    return sanitizeQuestionCache.get(html);
  }

  // Remove script tags
  let cleaned = html.replace(/<script\b[^<]*(?:(?!<\/script>)<[^<]*)*<\/script>/gi, '');

  // Strip intrusive inline styling from contentEditable
  cleaned = cleaned.replace(/font-family:\s*[^;"]*;?/gi, '');
  cleaned = cleaned.replace(/font-size:\s*[^;"]*;?/gi, '');
  cleaned = cleaned.replace(/line-height:\s*[^;"]*;?/gi, '');
  cleaned = cleaned.replace(/color:\s*(#fff(fff)?|white|rgb\(\s*255\s*,\s*255\s*,\s*255\s*\)|rgb\(\s*51\s*,\s*65\s*,\s*85\s*\));?/gi, '');
  cleaned = cleaned.replace(/background(-color)?:\s*[^;"]*;?/gi, '');

  // Clean empty style attributes
  cleaned = cleaned.replace(/\s*style=(["'])\s*\1/gi, '');

  // Unwrap useless spans that have no attributes left: <span>text</span> -> text
  let prev;
  let loops = 0;
  do {
    prev = cleaned;
    cleaned = cleaned.replace(/<span>([\s\S]*?)<\/span>/gi, '$1');
    loops++;
  } while (cleaned !== prev && loops < 10);

  // Replace &nbsp; with normal space
  cleaned = cleaned.replace(/&nbsp;/g, ' ');

  const result = cleaned.trim();
  if (sanitizeQuestionCache.size >= MAX_CACHE_SIZE) sanitizeQuestionCache.clear();
  sanitizeQuestionCache.set(html, result);
  return result;
}

/**
 * Splits any time string into 12-hour { time: 'HH:MM', period: 'AM'|'PM' }
 * Handles 24h ('23:59', '15:30'), 12h ('3:59', '03:59 PM', '10:00 AM'), Bengali digits, etc.
 */
export function parseTimeAndPeriod(rawTime) {
  if (!rawTime || typeof rawTime !== 'string') {
    return { time: '11:59', period: 'PM' };
  }
  const str = rawTime.trim();
  const isPm = /pm|রাত|বিকাল|সন্ধ্যা|দুপুর/i.test(str);
  const isAm = /am|সকাল|ভোর/i.test(str);

  // Convert Bengali numerals to English numerals
  const bengaliDigits = { '০':'0', '১':'1', '২':'2', '৩':'3', '৪':'4', '৫':'5', '৬':'6', '৭':'7', '৮':'8', '৯':'9' };
  const cleanStr = str.replace(/[০-৯]/g, d => bengaliDigits[d] || d);
  const match = cleanStr.match(/(\d{1,2}):(\d{2})/);

  if (match) {
    let h = parseInt(match[1], 10);
    const m = match[2];

    if (h >= 12) {
      const pmH = h > 12 ? h - 12 : 12;
      return {
        time: `${String(pmH).padStart(2, '0')}:${m}`,
        period: 'PM'
      };
    }

    if (h === 0) {
      return {
        time: `12:${m}`,
        period: 'AM'
      };
    }

    let period = 'PM';
    if (isAm) period = 'AM';
    else if (isPm) period = 'PM';

    return {
      time: `${String(h).padStart(2, '0')}:${m}`,
      period
    };
  }

  return {
    time: str || '11:59',
    period: isAm ? 'AM' : 'PM'
  };
}
